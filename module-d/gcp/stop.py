"""Stop only the eight owned Module D Deployments, after evidence is exported.

No resources are deleted. Scaling to zero destroys ephemeral Pod data, including
PostgreSQL contents, Jaeger traces, Prometheus history and receiver memory.
"""
import argparse
import importlib.util
import json
import os
from pathlib import Path

_spec = importlib.util.spec_from_file_location("module_d_gcp_deploy", Path(__file__).with_name("deploy.py"))
deploy = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(deploy)
Client, require_owned, snapshot = deploy.Client, deploy.require_owned, deploy.snapshot
NS = deploy.NS
APPLICATIONS = ("module-d-payments", "module-d-data")
OTHERS = ("module-d-prometheus", "module-d-alertmanager", "module-d-alert-receiver",
          "otel-collector", "module-d-jaeger", "module-d-postgres")
EXPECTED = set(APPLICATIONS + OTHERS)
CONTROL_OFF = """import json, os, tempfile
from pathlib import Path
assert os.environ.get('POD_NAMESPACE') == 'observability-chaos-d'
assert os.environ.get('DEPLOYMENT_ENVIRONMENT') == 'sandbox'
target = Path('/var/run/chaos/control.json')
with tempfile.NamedTemporaryFile(mode='w', dir=target.parent, prefix='stop-', delete=False) as handle:
    json.dump({'enabled': False}, handle)
    handle.flush()
    os.fsync(handle.fileno())
    temporary = handle.name
os.replace(temporary, target)
assert json.loads(target.read_text())['enabled'] is False
print(json.dumps({'chaos_control_disabled': True}))
"""


def check_inventory(namespace, deployments, replica_sets, pods, other_metadata):
    """Pure preflight: reject any unexpected ownership before the first write."""
    if not namespace or namespace.get("name") != NS:
        raise ValueError("The dedicated Module D namespace does not exist")
    require_owned(namespace)
    names = [item["metadata"]["name"] for item in deployments]
    if len(names) != len(EXPECTED) or set(names) != EXPECTED:
        raise ValueError("Expected exactly the eight Module D Deployments; refusing a partial or foreign inventory")
    by_uid = {}
    for item in deployments:
        meta = item["metadata"]
        require_owned(meta)
        if meta.get("namespace") != NS:
            raise ValueError("Cross-namespace Deployment")
        by_uid[meta["uid"]] = meta["name"]
    for kind, meta in other_metadata:
        # Automatically generated by Kubernetes, not an operator-created resource.
        if kind == "ConfigMap" and meta.get("name") == "kube-root-ca.crt":
            continue
        if meta.get("namespace") != NS:
            raise ValueError("Cross-namespace auxiliary resource")
        require_owned(meta)
    rs_to_deployment = {}
    for item in replica_sets:
        meta = item["metadata"]
        require_owned(meta)
        owners = [o for o in meta.get("ownerReferences", []) if o.get("kind") == "Deployment" and o.get("uid") in by_uid]
        if len(owners) != 1 or meta.get("namespace") != NS:
            raise ValueError("A ReplicaSet is not owned by one of the eight approved Deployments")
        rs_to_deployment[meta["uid"]] = by_uid[owners[0]["uid"]]
    controls = []
    for pod in pods:
        meta = pod["metadata"]
        require_owned(meta)
        owners = [o for o in meta.get("ownerReferences", []) if o.get("kind") == "ReplicaSet" and o.get("uid") in rs_to_deployment]
        if len(owners) != 1 or meta.get("namespace") != NS:
            raise ValueError("An unexpected Pod exists in the sandbox; no mutations performed")
        app = rs_to_deployment[owners[0]["uid"]]
        ready = any(c.get("type") == "Ready" and c.get("status") == "True" for c in pod.get("status", {}).get("conditions", []))
        if app in APPLICATIONS and ready and not meta.get("deletionTimestamp"):
            names = [c["name"] for c in pod["spec"]["containers"]]
            if names != [app]:
                raise ValueError("Unexpected business Pod containers")
            controls.append({"deployment": app, "pod": meta["name"], "pod_uid": meta["uid"], "container": app})
    return sorted(controls, key=lambda value: (value["deployment"], value["pod"]))


def collect(client):
    namespace = client.get("namespace", NS, metadata_only=True)
    deployments = (client.get("deployment", namespace=NS) or {"items": []})["items"]
    replica_sets = (client.get("replicaset", namespace=NS) or {"items": []})["items"]
    pods = (client.get("pod", namespace=NS) or {"items": []})["items"]
    metadata = []
    # API projection emits metadata only; especially do not retrieve Secret data.
    projection = 'jsonpath={range .items[*]}{.kind}{"\\t"}{.metadata}{"\\n"}{end}'
    raw = client.call(["get", "services,configmaps,secrets,networkpolicies", "-n", NS, "-o", projection])
    for line in raw.splitlines():
        if line.strip():
            kind, encoded = line.split("\t", 1)
            metadata.append((kind, json.loads(encoded)))
    controls = check_inventory(namespace, deployments, replica_sets, pods, metadata)
    summary = [{"name": d["metadata"]["name"], "uid": d["metadata"]["uid"],
                "replicas": d["spec"].get("replicas", 1), "ready_replicas": d.get("status", {}).get("readyReplicas", 0)}
               for d in deployments]
    return controls, sorted(summary, key=lambda item: item["name"])


def execute(client, controls, receipt, save):
    """Called only after all inventory ownership checks have passed."""
    receipt["status"] = "STOP_STARTED_NOT_COMPLETED"
    save()
    for target in controls:
        action = {"action": "disable_chaos_control", **target, "started_at": deploy.utc(), "status": "STARTED"}
        receipt["actions"].append(action)
        save()
        # The Pod must still have the same immutable UID and Module D ownership.
        live = client.get("pod", target["pod"], NS, metadata_only=True)
        require_owned(live)
        if live.get("uid") != target["pod_uid"]:
            raise ValueError("Business Pod identity changed after preflight")
        response = client.call(["exec", "-n", NS, target["pod"], "-c", target["container"],
                                "--", "python", "-c", CONTROL_OFF])
        if json.loads(response).get("chaos_control_disabled") is not True:
            raise RuntimeError("Control deactivation was not confirmed")
        action.update(status="CONFIRMED", completed_at=deploy.utc())
        save()
    for name in APPLICATIONS + OTHERS:
        current = client.get("deployment", name, NS, metadata_only=True)
        require_owned(current)
        expected_uid = next(d["uid"] for d in receipt["deployments_before"] if d["name"] == name)
        if current.get("uid") != expected_uid:
            raise ValueError("Deployment identity changed after preflight")
        action = {"action": "scale_zero", "deployment": name, "started_at": deploy.utc(), "status": "STARTED"}
        receipt["actions"].append(action)
        save()
        client.call(["scale", "deployment", name, "-n", NS, "--replicas=0"])
        action.update(status="REQUEST_ACCEPTED", completed_at=deploy.utc())
        save()
    final = (client.get("deployment", namespace=NS) or {"items": []})["items"]
    if {d["metadata"]["name"] for d in final} != EXPECTED or any(d["spec"].get("replicas", 1) != 0 for d in final):
        raise RuntimeError("Could not verify zero desired replicas for all eight Deployments")
    receipt["status"] = "SCALED_ZERO_POD_TERMINATION_NOT_YET_VERIFIED"
    receipt["desired_replicas_zero_verified_at"] = deploy.utc()
    save()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", required=True)
    parser.add_argument("--cluster", default="otel-lab")
    parser.add_argument("--location", default="us-central1")
    parser.add_argument("--out", type=Path, default=Path(".state/module-d/stop-receipt"))
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    os.umask(0o077)
    client = Client(args.project, args.location, args.cluster)
    controls, summary = collect(client)  # Complete all guards before any write.
    args.out.mkdir(parents=True, exist_ok=False)
    (args.out / ".gitignore").write_text("*\n", encoding="utf-8")
    before = snapshot(client)
    receipt = {"started_at": deploy.utc(), "project": args.project, "namespace": NS,
        "status": "PLAN_ONLY_NO_CHANGES", "deployments_before": summary,
        "ready_business_pods_to_disable": controls, "actions": [], "original_resources_before": before,
        "data_loss_notice": "Scaling to zero discards ephemeral database, traces, metric history and receiver memory; export evidence first.",
        "resources_deleted": False, "secret_values_read_or_saved": False}
    def save():
        (args.out / "receipt.json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    save()
    try:
        if args.apply:
            execute(client, controls, receipt, save)
    finally:
        after = snapshot(client)
        receipt.update(finished_at=deploy.utc(), original_resources_after=after,
                       original_resources_unchanged=before == after)
        save()
        if before != after:
            raise RuntimeError("Original shared resources changed during stop; inspect the saved hashes")
    print(json.dumps({"status": receipt["status"], "namespace": NS, "out": str(args.out),
        "resources_deleted": False, "original_resources_unchanged": True}))


if __name__ == "__main__":
    main()
